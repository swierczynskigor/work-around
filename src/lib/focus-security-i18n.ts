export function focusSecurityCopy(language: Language): Copy {
  return { en, pl, de, es, fr }[language] || en;
}
export function pinErrorText(error: unknown, language: Language): string {
  const t = focusSecurityCopy(language);
  if (error instanceof CommandError) {
    const messages: Record<string, string> = {
      PIN_FORMAT: t.pinFormat,
      PIN_INVALID: t.pinInvalid,
      PIN_LOCKED: t.pinLocked,
      PIN_NOT_CONFIGURED: t.pinMissing,
      PIN_DOMAINS: t.domainsInvalid,
    };
    if (error.code && messages[error.code]) return messages[error.code];
  }
  return error instanceof Error ? error.message : t.unavailable;
}
